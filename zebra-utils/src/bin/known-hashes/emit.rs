//! Known-hash chunk pin emission and `KnownHashListSpec` constant printing.
//!
//! Chunks are never written out or shipped: nodes fetch them from peers with
//! `get-hashes` and check them against the pins. This module only computes
//! each chunk's pin, with the same [`chunk_pin`] that nodes verify with, and
//! prints the constant block that pins them, ready to paste into
//! `zebra-chain`.

use std::fmt::Write as _;

use color_eyre::eyre::{bail, ensure, Result};

use zebra_chain::{
    block::SyncHashEntry,
    parameters::{
        known_hashes::{chunk_pin, KnownHashListSpec, CHUNK_HEIGHTS},
        Network,
    },
};

/// Returns the pin of each [`CHUNK_HEIGHTS`]-height chunk of `entries`, in
/// chunk order. The last chunk holds the remaining entries.
///
/// `entries` must have one entry per height, starting at genesis, and its
/// first hash must be `network`'s genesis hash.
pub fn chunk_pins(network: &Network, entries: &[SyncHashEntry]) -> Result<Vec<[u8; 32]>> {
    let Some(genesis) = entries.first() else {
        bail!("the known-hash list must contain at least the genesis block");
    };

    ensure!(
        genesis.hash == network.genesis_hash(),
        "the swept hash at height 0 is {}, but the {network} genesis hash is {}; \
         the sweep file is corrupted or for another network",
        genesis.hash,
        network.genesis_hash(),
    );

    // `CHUNK_HEIGHTS` is 50,000, so it fits in a `usize`.
    Ok(entries
        .chunks(CHUNK_HEIGHTS as usize)
        .map(chunk_pin)
        .collect())
}

/// Checks `pins` against the chunk arithmetic and verification of
/// [`KnownHashListSpec`], exactly as a node would check the chunks of
/// `entries`, which must cover `0..=max_height`.
pub fn self_check(
    max_height: u32,
    pins: &[[u8; 32]],
    network: &Network,
    entries: &[SyncHashEntry],
) -> Result<()> {
    let spec = KnownHashListSpec {
        max_height: zebra_chain::block::Height(max_height),
        chunk_heights: CHUNK_HEIGHTS,
        chunk_hashes: pins.to_vec().into(),
    };

    // `CHUNK_HEIGHTS` is 50,000, so it fits in a `usize`.
    for (index, chunk) in entries.chunks(CHUNK_HEIGHTS as usize).enumerate() {
        spec.verify_chunk(network, index, chunk)?;
    }

    Ok(())
}

/// Formats the `KnownHashListSpec` constant block for `pins`, ready to paste
/// into `zebra-chain/src/parameters/known_hashes.rs`.
///
/// `const_prefix` is the network part of the constant name (`MAINNET` or
/// `TESTNET`), and `max_height` is the reviewed highest height the list
/// covers. The output matches the [`KnownHashListSpec`] struct field for
/// field, so it compiles when pasted in. Each pin is preceded by its hex,
/// so reviewers can compare two independent runs at a glance.
pub fn spec_constant_block(const_prefix: &str, max_height: u32, pins: &[[u8; 32]]) -> String {
    let mut block = String::new();

    // Writing to a `String` is infallible, so the `expect`s below hold.
    writeln!(
        block,
        "/// The {const_prefix} known-hash list: {} heights (0..={max_height}) in {} chunks,\n\
         /// generated by the `known-hashes` tool from a checkpoint-anchored sweep.\n\
         pub const {const_prefix}_KNOWN_HASHES: KnownHashListSpec = KnownHashListSpec {{\n\
         \x20   max_height: block::Height({max_height}),\n\
         \x20   chunk_heights: CHUNK_HEIGHTS,\n\
         \x20   chunk_hashes: Cow::Borrowed(&[",
        u64::from(max_height) + 1,
        pins.len(),
    )
    .expect("writing to a String never fails");

    for (index, pin) in pins.iter().enumerate() {
        let bytes = pin
            .iter()
            .map(|byte| format!("0x{byte:02x}"))
            .collect::<Vec<_>>()
            .join(", ");

        writeln!(
            block,
            "        // {index}: {}\n        [{bytes}],",
            hex::encode(pin)
        )
        .expect("writing to a String never fails");
    }

    writeln!(block, "    ]),\n}};").expect("writing to a String never fails");

    block
}
